function split(
  id: string,
  status: SplitInstruction["status"],
  scene: SplitInstruction["transactionScene"],
  allocationBase: number,
  merchantAmount: number,
  platformAmount: number,
  channelFeeAmount: number,
  rewardAmount: number,
): SplitInstruction {
  return {
    id,
    splitInstructionNo: `SPLIT-${id.toUpperCase()}`,
    orderId: `ORDER-${id.toUpperCase()}`,
    merchantId: id === "s3" ? "M002" : "M001",
    shopId: id === "s3" ? "S003" : "S001",
    transactionScene: scene,
    profileSnapshotId: id === "s3" ? "profile-m002-v3" : "profile-m001-v1",
    profileVersion: id === "s3" ? 3 : 1,
    allocationBase,
    merchantAmount,
    platformAmount,
    channelFeeAmount,
    rewardPointCashEquivalent: rewardAmount,
    roundingAmount: allocationBase - merchantAmount - platformAmount - channelFeeAmount - rewardAmount,
    settlementEligibleAt: "2026-07-01 10:00:00",
    scheduledSettlementDate: id === "s3" ? "2026-07-04" : "2026-07-02",
    idempotentKey: `split:${id}:v1`,
    attemptCount: status === "FAILED" || status === "PARTIAL" ? 2 : 1,
    lastErrorCode: status === "FAILED" ? "CHANNEL_TIMEOUT" : status === "PARTIAL" ? "PARTIAL_RECEIVER_FAILED" : null,
    lastErrorMessage: status === "FAILED" ? "Mock 渠道超时" : status === "PARTIAL" ? "Mock 用户返积分分配失败" : null,
    status,
    reconciliationStatus: status === "PARTIAL" ? "MISMATCH" : status === "SUCCESS" ? "MATCHED" : "NOT_STARTED",
    updatedAt: "2026-07-01 10:01:00",
    createdAt: "2026-07-01 10:00:00",
  };
}

